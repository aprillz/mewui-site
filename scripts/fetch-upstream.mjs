// Collects the facts the landing page states, straight from the MewUI repository
// and the NuGet registry. Nothing here is transcribed by hand into the page.
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const RAW = "https://raw.githubusercontent.com/aprillz/MewUI/main";
const NUGET_INDEX =
  "https://api.nuget.org/v3-flatcontainer/aprillz.mewui/index.json";
const NUGET_SEARCH =
  "https://azuresearch-usnc.nuget.org/query?q=packageid:aprillz.mewui&prerelease=false";
const GITHUB_REPO = "https://api.github.com/repos/aprillz/MewUI";

const OUT = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../src/data/upstream.json",
);

const githubHeaders = {
  "user-agent": "mewui-site",
  accept: "application/vnd.github+json",
  ...(process.env.GITHUB_TOKEN
    ? { authorization: `Bearer ${process.env.GITHUB_TOKEN}` }
    : {}),
};

async function get(url, kind, headers = {}) {
  const response = await fetch(url, {
    headers: { "user-agent": "mewui-site", ...headers },
  });
  if (!response.ok) {
    throw new Error(`${kind}: ${url} responded ${response.status}`);
  }
  return kind === "json" ? response.json() : response.text();
}

// The releases endpoint pages at 30, so the count lives in the last page link.
async function countReleases() {
  const response = await fetch(`${GITHUB_REPO}/releases?per_page=1`, {
    headers: githubHeaders,
  });
  if (!response.ok) {
    throw new Error(`releases: responded ${response.status}`);
  }
  const link = response.headers.get("link") ?? "";
  const last = link.match(/[?&]page=(\d+)>; rel="last"/);
  if (last !== null) {
    return Number(last[1]);
  }
  return (await response.json()).length;
}

function requireMatch(text, pattern, what) {
  const match = text.match(pattern);
  if (match === null) {
    throw new Error(`Could not find ${what} upstream. The source layout changed.`);
  }
  return match[1].trim();
}

const props = await get(`${RAW}/build/MewUI.Common.props`, "text");
const repoVersion = requireMatch(
  props,
  /<MewUIVersion>([^<]+)<\/MewUIVersion>/,
  "MewUIVersion",
);
const targetFrameworks = requireMatch(
  props,
  /<MewUITargetFrameworks>([^<]+)<\/MewUITargetFrameworks>/,
  "MewUITargetFrameworks",
);

const sizes = await get(`${RAW}/tools/aot-size/release-sizes.json`, "json");
if (sizes.schemaVersion !== 2) {
  throw new Error(
    `release-sizes.json is schemaVersion ${sizes.schemaVersion}, expected 2.`,
  );
}
if (!Array.isArray(sizes.entries) || sizes.entries.length === 0) {
  throw new Error("release-sizes.json carries no entries.");
}

const readme = await get(`${RAW}/README.md`, "text");
const tryCommand = requireMatch(
  readme,
  /^(curl -sL https:\/\/raw\.githubusercontent\.com\/aprillz\/MewUI\/.+)$/m,
  "the try-it-out one liner",
);

const nuget = await get(NUGET_INDEX, "json");
const stable = nuget.versions.filter((version) => !version.includes("-"));
const publishedVersion = stable[stable.length - 1];
if (publishedVersion === undefined) {
  throw new Error("NuGet returned no stable Aprillz.MewUI version.");
}

const repo = await get(GITHUB_REPO, "json", githubHeaders);
const releaseCount = await countReleases();

const search = await get(NUGET_SEARCH, "json");
const downloads = search.data?.[0]?.totalDownloads;
if (typeof downloads !== "number") {
  throw new Error("NuGet search returned no download count.");
}

if (sizes.mewUIVersion !== repoVersion) {
  console.warn(
    `[fetch-upstream] size data was measured on ${sizes.mewUIVersion} but the repository is at ${repoVersion}. The size table is stale.`,
  );
}

const upstream = {
  fetchedAt: new Date().toISOString(),
  repoVersion,
  publishedVersion,
  targetFrameworks: targetFrameworks.split(";"),
  tryCommand,
  stats: {
    stars: repo.stargazers_count,
    forks: repo.forks_count,
    releases: releaseCount,
    downloads,
  },
  sizes: {
    measuredOnVersion: sizes.mewUIVersion,
    generatedAtUtc: sizes.generatedAtUtc,
    entries: sizes.entries,
  },
};

await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, `${JSON.stringify(upstream, null, 2)}\n`, "utf8");

// The snippets project compiles against whatever is actually on NuGet.
await writeFile(
  resolve(dirname(OUT), "../../snippets/Directory.Build.props"),
  [
    "<Project>",
    "  <!-- Generated by scripts/fetch-upstream.mjs. Do not edit. -->",
    "  <PropertyGroup>",
    `    <MewUIPackageVersion>${publishedVersion}</MewUIPackageVersion>`,
    "  </PropertyGroup>",
    "</Project>",
    "",
  ].join("\n"),
  "utf8",
);
console.log(
  `[fetch-upstream] ${repoVersion} in repo, ${publishedVersion} on NuGet, ${sizes.entries.length} size rows, ${repo.stargazers_count} stars, ${releaseCount} releases, ${downloads} downloads.`,
);
